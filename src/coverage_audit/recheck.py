"""The second check of the coverage-audit matches (decisions 0031, 0032): about 10% of the sample, matched again.

`sheet` writes the entries marked `recheck` in the sample as a sheet of their own, with the same candidates and
searches but none of the first answers, so the second pass is blind to the first. It is best done a few days after
the first pass, or by a second person. `agreement` compares the two passes: the share of entries where both give
the same item (or both say none), with a Wilson 95% interval, and lists every disagreement for a look.

Usage:
    uv run python -m src.coverage_audit.recheck sheet
    uv run python -m src.coverage_audit.recheck agreement
Files:
    results/coverage_audit/recheck_sheet_v1.csv    for the second pass: fill in `match`
    results/coverage_audit/recheck_v1.json, .md     agreement and the disagreements
"""

import argparse
import csv
import json
from datetime import UTC, datetime

from src.coverage_audit.fill import QID, read_csv, wilson
from src.coverage_audit.sample import RESULTS, SHEET_COLUMNS

SHEET = RESULTS / "match_sheet_v1.csv"
SAMPLE = RESULTS / "sample_v1.csv"
RECHECK = RESULTS / "recheck_sheet_v1.csv"
OUT = RESULTS / "recheck_v1"


def normalise(match: str) -> str:
    m = match.strip()
    return m.lower() if m.lower() == "none" else m


def sheet() -> None:
    if RECHECK.exists() and any(r["match"].strip() for r in read_csv(RECHECK)):
        raise SystemExit(f"{RECHECK.name} already has second-pass answers; it is never rewritten")
    marked = {r["sample_id"] for r in read_csv(SAMPLE) if r["recheck"]}
    # Same candidates; the first pass's match, searches and notes are left out, since the author's additions to
    # `searched` cannot be told apart from the automatic ones reliably.
    rows = [{**r, "match": "", "searched": "", "notes": ""} for r in read_csv(SHEET) if r["sample_id"] in marked]
    with open(RECHECK, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=SHEET_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"{RECHECK.name}: {len(rows)} entries for the second pass")


def agreement() -> None:
    first = {r["sample_id"]: normalise(r["match"]) for r in read_csv(SHEET)}
    second = {r["sample_id"]: normalise(r["match"]) for r in read_csv(RECHECK)}
    bad = [s for s, m in {**first, **second}.items() if m and not (QID.match(m) or m == "none")]
    if bad:
        raise SystemExit(f"`match` must be a QID or none: {', '.join(sorted(set(bad)))}")
    both = [s for s in second if second[s] and first.get(s)]
    same = [s for s in both if first[s] == second[s]]
    lo, hi = wilson(len(same), len(both))
    report = {
        "generated": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "entries_marked": len(second),
        "compared": len(both),
        "agree": len(same),
        "share": round(len(same) / len(both), 3) if both else None,
        "ci95": [lo, hi],
        "disagreements": [{"sample_id": s, "first": first[s], "second": second[s]} for s in both if s not in same],
    }
    OUT.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n")
    lines = [
        "# Coverage audit: second check of the matches",
        "",
        f"Generated by `src/coverage_audit/recheck.py` on {report['generated'][:10]} (decisions 0031, 0032). "
        f"Compared {report['compared']} of {report['entries_marked']} entries marked for a second pass.",
        "",
    ]
    if both:
        lines.append(
            f"Same answer in both passes: {len(same)} of {len(both)} ({report['share']:.0%}, Wilson 95% [{lo:.0%}, {hi:.0%}])."
        )
    if report["disagreements"]:
        lines += ["", "| Entry | First pass | Second pass |", "| --- | --- | --- |"]
        lines += [f"| {d['sample_id']} | {d['first']} | {d['second']} |" for d in report["disagreements"]]
    OUT.with_suffix(".md").write_text("\n".join(lines) + "\n")
    print(f"agree on {len(same)} of {len(both)}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("step", choices=["sheet", "agreement"])
    {"sheet": sheet, "agreement": agreement}[parser.parse_args().step]()


if __name__ == "__main__":
    main()
