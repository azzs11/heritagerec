"""The interim checkpoint report of 30 November 2026 (specification Section 10), labelled interim throughout.

Gathers what the checkpoint asks for from the files that produce it, and writes nothing by hand: the snapshot and
its checksum, the data card, the graph statistics, the benchmark queries and split, the judge's pilot agreement,
the baselines on the 40 dev queries, and the coverage audit's progress. A part whose file does not exist yet is
listed as not available, with the file it waits for; no number is filled in. The test split stays sealed.

Usage:
    uv run python -m src.benchmark.interim
Output:
    results/interim/checkpoint_v1.md and .json
"""

import json
import subprocess
from datetime import UTC, datetime
from pathlib import Path

from src.corpus.wikimedia import ROOT

SOURCES = {
    "snapshot": ROOT / "data/corpus_v1/manifest.json",
    "graph": ROOT / "results/graph/core_v1.json",
    "queries": ROOT / "results/queries/split_v1.json",
    "pool": ROOT / "results/judging/dev_pool_v1.json",
    "judge_pilot": ROOT / "results/judging/dev_pilot_agreement_v1.json",
    "baselines": ROOT / "results/benchmark/dev_v1/summary.json",
    "coverage_audit": ROOT / "results/coverage_audit/coverage_v1.json",
}
OUT = ROOT / "results/interim/checkpoint_v1"
LABEL = "INTERIM (30 Nov 2026 checkpoint): dev split only, corpus not frozen; every number here will change."


def load(path: Path) -> dict | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def gather() -> dict:
    data = {k: load(p) for k, p in SOURCES.items()}
    return {
        "label": LABEL,
        "generated": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "commit": subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip(),
        "sources": {k: str(p.relative_to(ROOT)) for k, p in SOURCES.items()},
        "available": {k: v is not None for k, v in data.items()},
        **data,
    }


def waiting(report: dict, key: str) -> list[str]:
    return [f"Not available yet: waits for `{report['sources'][key]}`.", ""]


def markdown(r: dict) -> str:
    out = [
        "# Interim checkpoint",
        "",
        f"**{r['label']}**",
        "",
        f"Generated by `src/benchmark/interim.py` on {r['generated'][:10]} at commit `{r['commit']}` from the files "
        "named in each section; nothing is written by hand. The test split stays sealed.",
        "",
        "## Corpus snapshot",
        "",
    ]
    s = r["snapshot"]
    if s:
        snap = s["snapshot"]
        out += [
            f"`{snap['path']}`: {snap['records']:,} documents, SHA-256 `{snap['sha256']}`, built {s['built'][:10]} at "
            f"commit `{s['commit'][:7]}`. The data card is `docs/data_card.md`.",
            "",
            "| Language | Documents |",
            "| --- | --- |",
            *[f"| {k} | {v:,} |" for k, v in s["records_by_language"].items()],
            "",
            "| Document type | Documents |",
            "| --- | --- |",
            *[f"| {k} | {v:,} |" for k, v in s["records_by_doc_type"].items()],
            "",
        ]
    else:
        out += waiting(r, "snapshot")

    out += ["## Knowledge graph (core Wikidata layer)", ""]
    g = r["graph"]
    if g:
        st = g["stats"]
        out += [
            f"{st['nodes']:,} nodes and {st['edges']:,} edges (`results/graph/core_v1.md` has the full statistics).",
            "",
            "| Node kind | Nodes |",
            "| --- | --- |",
            *[f"| {k} | {v:,} |" for k, v in st["nodes_by_kind"].items()],
            "",
        ]
    else:
        out += waiting(r, "graph")

    out += ["## Benchmark queries", ""]
    q = r["queries"]
    if q:
        out += [
            f"{q['queries']} queries, split {q['by_split']}; linkable entity in "
            f"{q['linkable_share_overall']:.0%} of queries; test file SHA-256 `{q['test_sha256']}` (sealed).",
            "",
            "| Sparse-tier quota (decision 0031) | Needed | Have |",
            "| --- | --- | --- |",
            *[f"| {k} | {v['needed']} | {v['have']} |" for k, v in q["sparse_quota"].items()],
            "",
        ]
    else:
        out += waiting(r, "queries")

    out += ["## Relevance judge (Gemma 4 31B) against the author", ""]
    j = r["judge_pilot"]
    if j:
        o = j["overall"]
        out += [
            f"Pilot on {o['n']} dev pairs: weighted kappa (linear) {o['weighted_kappa_linear']}, raw agreement "
            f"{o['raw_agreement']}.",
            "",
            "| Query language | Pairs | Weighted kappa |",
            "| --- | --- | --- |",
            *[f"| {k} | {v['n']} | {v.get('weighted_kappa_linear', '')} |" for k, v in j["by_query_language"].items()],
            "",
        ]
    else:
        out += waiting(r, "judge_pilot")
    if r["pool"]:
        p = r["pool"]
        out += [f"Dev pool: {p['pairs']} pairs from {len(p['runs'])} runs at depth {p['depth']}.", ""]

    out += ["## Baselines on the 40 dev queries", ""]
    b = r["baselines"]
    if b:
        primary = b["settings"]["primary"]
        out += [
            f"{b['queries_scored']} queries scored ({len(b['queries_without_relevant_judgement'])} without a relevant "
            f"document). {primary} with 95% bootstrap intervals; `results/benchmark/dev_v1/summary.md` has every measure.",
            "",
            f"| System | {primary} | Unjudged in top 10 |",
            "| --- | --- | --- |",
        ]
        for name, sys in b["systems"].items():
            v = sys["measures"][primary]
            out.append(
                f"| {name} | {v['mean']:.3f} [{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}] | {sys['unjudged_in_top10']} |"
            )
        out.append("")
    else:
        out += waiting(r, "baselines")

    out += ["## Coverage audit (decisions 0031, 0032)", ""]
    c = r["coverage_audit"]
    if c:
        out += [f"Author's matching: {c['progress']}. Rates are in `results/coverage_audit/coverage_v1.md`.", ""]
    else:
        out += waiting(r, "coverage_audit")
    return "\n".join(out) + "\n"


def main() -> None:
    report = gather()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.with_suffix(".json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    OUT.with_suffix(".md").write_text(markdown(report))
    print(f"wrote {OUT.with_suffix('.md').relative_to(ROOT)}; available: {report['available']}")


if __name__ == "__main__":
    main()
